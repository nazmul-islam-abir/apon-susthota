// ---------------------------------------------------------------------
//  FoodItem model (kept here for separation from legacy code; legacy
//  model in api_service.dart still exists but the active one is this).
// ---------------------------------------------------------------------

class FoodItem {
  const FoodItem({
    required this.id,
    required this.nameEn,
    required this.category,
    required this.servingG,
    required this.kcalPerServing,
    required this.proteinG,
    required this.carbsG,
    required this.fatG,
    required this.fiberG,
    this.nameBn,
    this.description,
  });

  final String id;
  final String nameEn;
  final String? nameBn;
  final String category;
  final double servingG;
  final double kcalPerServing;
  final double proteinG;
  final double carbsG;
  final double fatG;
  final double fiberG;
  final String? description;

  String get displayName =>
      (nameBn != null && nameBn!.isNotEmpty) ? nameBn! : nameEn;
  double get kcal => kcalPerServing;
  String get imageUrl => BdFoodLibrary.imageFor(id);
}
